export function translateMessage(
  rawText: string,
  targetCode: TypeCode,
  relation: Relation
): Suggestion[] {
  const t = getType(targetCode);
  const patterns = PROFILES[targetCode];
  if (!t || !patterns) return [];
  const core = trimEnd(rawText);
  if (!core) return [];

  return patterns.map((p) => ({
    label: p.label,
    example: p.wrap(core, relation),
    why: p.why,
  }));
}
