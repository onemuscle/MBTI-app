import { AXIS_SCORES, TypeCode, getType } from "@/data/atlas";

// シーン別カード（設計書4章）。相手タイプの軸傾向に合わせて
// 「組み立て手順・例文・避けたいこと」をルールベースで生成する。

export const SCENES = [
  { slug: "apologize", label: "謝る", icon: "🙇" },
  { slug: "invite", label: "誘う", icon: "🙌" },
  { slug: "decline", label: "断る", icon: "🙅" },
  { slug: "consult", label: "相談する", icon: "💬" },
  { slug: "praise", label: "褒める", icon: "🌟" },
  { slug: "feedback", label: "指摘する", icon: "📝" },
  { slug: "confess", label: "告白する", icon: "💌" },
  { slug: "distance", label: "距離を置く", icon: "🌙" },
] as const;

export type SceneSlug = (typeof SCENES)[number]["slug"];

export interface SceneGuide {
  steps: { title: string; detail: string }[];
  examples: string[];
  ng: string[];
}

export function buildSceneGuide(slug: SceneSlug, code: TypeCode): SceneGuide | null {
  const t = getType(code);
  const ax = AXIS_SCORES[code];
  if (!t || !ax) return null;

  // 相手の傾向（タイプの軸スコアから判定）
  const feeling = ax.decision >= 50; // 価値・関係で決める
  const thinksFirst = ax.speed < 50; // 考えてから話す
  const planner = ax.planning < 50; // 確定・締切を好む
  const lowExpr = ax.expression < 50; // 感情は内で処理
  const role = t.role;

  const steps: { title: string; detail: string }[] = [];
  const examples: string[] = [];
  const ng: string[] = [];

  switch (slug) {
    case "apologize":
      if (feeling) {
        steps.push(
          { title: "気持ちへの影響を先に認める", detail: `${role}タイプは「反省しているか」より先に「嫌な思いをさせたと分かっているか」を見ています。まず相手の気持ちに触れましょう。` },
          { title: "事実を言い訳なしで認める", detail: "「でも」「だって」を挟まず、何をしたかをそのまま認めます。" },
          { title: "これからどうするかを一つ伝える", detail: "大げさな誓いより、次から変える具体的な一つを。" }
        );
        examples.push(
          "嫌な思いをさせてごめん。あの言い方は良くなかった。次からは先にあなたの話を聞くようにする。",
          "昨日のこと、ずっと考えてた。悲しませたことが一番申し訳ない。埋め合わせさせてほしい。"
        );
      } else {
        steps.push(
          { title: "結論（謝罪）から入る", detail: `${role}タイプには前置きの長い謝罪は逆効果。最初の一文で認めます。` },
          { title: "原因と再発防止を具体的に", detail: "感情の吐露より「なぜ起きたか」「次どう防ぐか」が誠意として伝わります。" },
          { title: "埋め合わせは実務で", detail: "「今回の遅れはこうリカバリーする」と行動で示すのが最も効きます。" }
        );
        examples.push(
          "遅れてすみません。原因は見積もりの甘さです。次からは前日に一度進捗を共有します。",
          "先日は約束を破ってごめん。今後は難しくなった時点ですぐ連絡するようにする。"
        );
      }
      ng.push("言い訳とセットの謝罪（「ごめん、でも…」）");
      ng.push(feeling ? "事実の正しさだけを主張して気持ちに触れない" : "感情的な自己弁護を長々と続ける");
      break;

    case "invite":
      if (planner) {
        steps.push(
          { title: "日時・場所・所要時間を先に示す", detail: `${role}タイプは予定が具体的なほど動きやすいタイプ。「今度」より「来週土曜の昼」。` },
          { title: "内容と理由を一言添える", detail: "「あなたが好きそうだと思って」と選んだ理由があると安心されます。" },
          { title: "断りやすい逃げ道も用意", detail: "「無理なら別日で」の一言で、義理での参加を防げます。" }
        );
        examples.push(
          "来週土曜の12時から、駅前の新しい定食屋に行かない？1時間くらいで解散予定。都合悪ければ再来週でも。",
          "◯日の夜、映画どう？あなたが前に話してた監督の新作。チケットは私が取っておくよ。"
        );
      } else {
        steps.push(
          { title: "面白さ・ワクワクを先に伝える", detail: `${role}タイプは「楽しそうかどうか」で動くタイプ。企画の魅力から入りましょう。` },
          { title: "細部は決めすぎない", detail: "全部確定した計画より「行きながら決めよう」の余白が心地よいことも。" },
          { title: "軽く誘って反応を見る", detail: "重い招待状より「ふと思ったんだけど」くらいの温度感が乗りやすい。" }
        );
        examples.push(
          "面白そうな屋台フェス見つけた！今週末ふらっと行かない？",
          "急だけど今夜空いてる？例の店、今日なら入れるらしい。"
        );
      }
      if (thinksFirst) ng.push("その場での即答を迫る（考える時間があると参加率が上がります）");
      ng.push("参加を断られたときに理由を問い詰める");
      break;

    case "decline":
      if (feeling) {
        steps.push(
          { title: "誘ってくれたことへの感謝から", detail: `${role}タイプは断られる=関係の否定と受け取りやすいので、まず「誘いは嬉しい」を伝えます。` },
          { title: "理由は正直に、短く", detail: "凝った言い訳より「疲れていて」の正直さが信頼につながります。" },
          { title: "次につながる一言を添える", detail: "「また誘ってほしい」「来月なら」で関係は減点されません。" }
        );
        examples.push(
          "誘ってくれてありがとう！今週は疲れが溜まってて休みたい日なんだ。また絶対誘ってね。",
          "行きたい気持ちは山々なんだけど、今回は見送らせて。来月なら動けそう！"
        );
      } else {
        steps.push(
          { title: "結論を最初にはっきり", detail: `${role}タイプには曖昧な保留が一番のストレス。「行けない」を先に。` },
          { title: "理由は事実ベースで一つ", detail: "長い言い訳は不要。事実を一つ言えば納得されます。" },
          { title: "代替案があれば具体的に", detail: "「代わりに◯日なら」まで言えると誠実さが伝わります。" }
        );
        examples.push(
          "その日は先約があって行けない。◯日なら空いてるけどどう？",
          "今回はパスさせて。今月は仕事の山場で余裕がないんだ。"
        );
      }
      ng.push("返事を保留したままフェードアウトする");
      ng.push("行けない理由を盛りすぎて後でバレる");
      break;

    case "consult":
      if (thinksFirst) {
        steps.push(
          { title: "先に文字で概要を送る", detail: `${role}タイプは考える時間があるほど良い答えをくれます。相談内容を先にメッセージで。` },
          { title: "聞きたいことを明確にする", detail: "「どう思う？」より「AとBならどっちが良いと思う？」が答えやすい。" },
          { title: "急かさない", detail: "「今週中に意見もらえたら嬉しい」と期限だけ渡して待ちましょう。" }
        );
      } else {
        steps.push(
          { title: "会話の中で相談する", detail: `${role}タイプは話しながら考えるタイプ。文章より対話でアイデアが出ます。` },
          { title: "状況を手短かに、あとは壁打ち", detail: "背景説明は最小限にして、一緒に考えてもらう形が合います。" },
          { title: "出たアイデアを一緒に面白がる", detail: "途中のアイデアを否定せず転がすと、どんどん良い案が出ます。" }
        );
      }
      steps.push(
        feeling
          ? { title: "「聞いてほしいだけ」かを先に伝える", detail: "解決策が欲しいのか、共感が欲しいのかを最初に言うとすれ違いません。" }
          : { title: "解決してほしいのか明示する", detail: `${role}タイプは相談=解決要請と受け取りがち。「アドバイスが欲しい」と言えば全力で考えてくれます。` }
      );
      examples.push(
        thinksFirst
          ? "折り入って相談があって。◯◯のことで迷ってる。詳細を送るから、今週どこかで意見聞かせてほしい。"
          : "ちょっと相談乗ってくれない？◯◯で迷ってて、話しながら整理したい。"
      );
      ng.push("結論のない長い前置きを続ける");
      ng.push("もらったアドバイスを全部否定する");
      break;

    case "praise":
      if (feeling) {
        steps.push(
          { title: "人柄・気遣いを褒める", detail: `${role}タイプは成果より「あなたのおかげで助かった」「気遣いが嬉しかった」が深く刺さります。` },
          { title: "具体的なエピソードで", detail: "「あの時の一言に救われた」と場面を特定すると本物の言葉になります。" },
          { title: "第三者にも伝わる形で", detail: "本人のいないところでも褒めると、巡り巡って何倍も嬉しい。" }
        );
        examples.push(
          "この前フォローしてくれたの、本当に助かった。あなたのそういうところ尊敬してる。",
          "◯◯さんが場を和ませてくれるから、みんな安心して話せてるんだと思う。"
        );
      } else {
        steps.push(
          { title: "能力と成果を具体的に褒める", detail: `${role}タイプはお世辞に敏感。「すごい」より「この判断が効いた」と根拠付きで。` },
          { title: "大げさにしない", detail: "事実ベースの淡々とした承認の方が、誇張された賞賛より信頼されます。" },
          { title: "任せる形で信頼を示す", detail: "「次もあなたに頼みたい」は、このタイプへの最高の褒め言葉です。" }
        );
        examples.push(
          "あの場面での判断、的確だった。あれがなかったら間に合わなかったと思う。",
          "資料の構成が分かりやすかった。次の案件も相談させてほしい。"
        );
      }
      ng.push("人前で過剰に持ち上げる（タイプによっては居心地が悪くなります）");
      ng.push("褒めた直後に頼み事をする（打算に見えます）");
      break;

    case "feedback":
      if (feeling) {
        steps.push(
          { title: "1対1の場を選ぶ", detail: `${role}タイプへの指摘は必ず個別で。人前での指摘はその後の関係に長く残ります。` },
          { title: "貢献を認めてから本題へ", detail: "「いつも助かってる。その上で一つだけ」の順番で、防御反応を防ぎます。" },
          { title: "行動の話に限定する", detail: "「あなたは◯◯な人」ではなく「この場面のこのやり方」の話にします。" },
          { title: "一緒に改善策を考える", detail: "「どうしたらやりやすくなる？」と本人の案を引き出すと前向きに変わります。" }
        );
        examples.push(
          "いつも丁寧にやってくれて助かってる。一つだけ、報告のタイミングをもう半日早くできると、もっとスムーズになりそう。どうかな？"
        );
      } else {
        steps.push(
          { title: "前置きなしで要点から", detail: `${role}タイプは遠回しな指摘を「回りくどい」と感じます。率直さがむしろ敬意になります。` },
          { title: "事実と根拠で示す", detail: "印象ではなくデータや具体例で。論理が通っていれば素直に受け入れるタイプです。" },
          { title: "代替案とセットで", detail: "「ダメ」で終わらせず「こうした方が速い」まで言うと建設的な議論になります。" }
        );
        examples.push(
          "一点だけ指摘させて。この手順だと後工程で手戻りが出る。先にレビューを挟む方が結果的に速いと思う。どう思う？"
        );
      }
      ng.push("溜め込んだ不満をまとめて一気に出す");
      ng.push(feeling ? "正論で追い詰めて逃げ場をなくす" : "根拠を示さず印象だけで指摘する");
      break;

    case "confess":
      if (thinksFirst) {
        steps.push(
          { title: "二人きりの落ち着いた場面で", detail: `${role}タイプはサプライズや公開の場が苦手。静かな環境で、逃げ場のある形で伝えます。` },
          { title: "気持ちはシンプルに、明確に", detail: "回りくどい表現は誤解のもと。「好きです。付き合ってほしい」を明確に。" },
          { title: "考える時間を渡す", detail: "「すぐ返事しなくていい」の一言が最大の思いやり。即答を求めると防御的になります。" }
        );
        examples.push(
          "ずっと伝えたかったんだけど、あなたのことが好きです。急がないので、考えてもらえたら嬉しい。"
        );
      } else {
        steps.push(
          { title: "気持ちはまっすぐ伝える", detail: `${role}タイプは駆け引きより素直さに心が動きます。` },
          { title: "好きになった理由を具体的に", detail: "「あなたのこういうところが好き」が伝わると、社交辞令ではなく本気だと分かります。" },
          { title: "重くしすぎない", detail: "深刻な空気より、明るさの中に本気が見える伝え方が受け取りやすいタイプです。" }
        );
        examples.push(
          "一緒にいると本当に楽しくて、気づいたら好きになってた。よかったら付き合ってください。"
        );
      }
      ng.push("お酒の勢いや冗談めかした告白（本気度が伝わりません）");
      ng.push("返事を急かす・保留を責める");
      break;

    case "distance":
      steps.push(
        { title: "黙って消えない", detail: "どのタイプにも、無言のフェードアウトは最も不安と不信を残します。一言だけ伝えましょう。" },
        lowExpr
          ? { title: "理由を簡潔に、詮索はしない前提で", detail: `${role}タイプ自身も一人の時間を大切にするタイプ。「自分の問題で少し時間がほしい」で十分伝わります。` }
          : { title: "「嫌いになったわけではない」を明確に", detail: `${role}タイプは距離=拒絶と受け取りやすいタイプ。関係自体は大切だと言葉にします。` },
        { title: "期間の目安を伝える", detail: "「少しの間」より「今月いっぱいは」の方が、相手は安心して待てます。" }
      );
      examples.push(
        lowExpr
          ? "ちょっと自分のことで考えたいことがあって、今月は一人の時間を多めに取るね。落ち着いたらまた連絡する。"
          : "あなたが嫌になったわけじゃなくて、自分に余裕がなくて。今月いっぱい少し距離をもらえたら、ちゃんと戻ってくるから。"
      );
      ng.push("既読無視・ブロックで察してもらおうとする");
      ng.push("距離を置く理由を相手のせいにする");
      break;
  }

  // タイプ図鑑のDON'Tから、このタイプ固有の地雷を補足
  for (const d of t.communication_dont.slice(0, 2)) {
    if (!ng.includes(d)) ng.push(d);
  }

  return { steps, examples, ng: ng.slice(0, 4) };
}
